#!/usr/bin/env node
/**
 * Refresh the list of disposable (throwaway) email domains the site refuses
 * at registration (PROMPT-39, part C).
 *
 *   node --use-system-ca scripts/update-disposable-domains.mjs
 *   node --use-system-ca scripts/sync-auth-domains.mjs --apply
 *
 * The first command downloads the community list — CC0 1.0, public domain —
 * from https://github.com/disposable-email-domains/disposable-email-domains
 * and rewrites lib/auth/disposable-domains.list.ts. The second puts the new
 * list into the database, where the Before User Created hook reads it, and
 * regenerates supabase/seed/auth_domains.sql; tests/unit/auth-domains-sync.test.ts
 * fails until it has been run. Run both from time to time; nothing fetches
 * the list while the site is running.
 *
 * `--use-system-ca` is only for machines whose antivirus inspects HTTPS (like
 * the owner's); it does no harm elsewhere.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const REPOSITORY = "disposable-email-domains/disposable-email-domains";
const LIST_URL = `https://raw.githubusercontent.com/${REPOSITORY}/main/disposable_email_blocklist.conf`;
const COMMIT_URL = `https://api.github.com/repos/${REPOSITORY}/commits/main`;
const OUT = join(process.cwd(), "lib", "auth", "disposable-domains.list.ts");

/** A plain host name: letters, digits, hyphens and dots, at least one dot. */
const DOMAIN = /^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+$/;

async function text(url, headers = {}) {
  const response = await fetch(url, { headers: { "user-agent": "bilimhezinisi-list-update", ...headers } });
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  return response.text();
}

const raw = await text(LIST_URL);
let commit = "unknown";
try {
  commit = JSON.parse(await text(COMMIT_URL, { accept: "application/vnd.github+json" })).sha ?? "unknown";
} catch {
  // The list itself is what matters; the commit is provenance only.
}

const domains = [
  ...new Set(
    raw
      .split(/\r?\n/)
      .map((line) => line.trim().toLowerCase())
      .filter((line) => line && !line.startsWith("#") && DOMAIN.test(line)),
  ),
].sort();

if (domains.length < 1000) {
  throw new Error(`only ${domains.length} domains came back — refusing to overwrite the list`);
}

const fetched = new Date().toISOString().slice(0, 10);
const body = [
  "// Generated by scripts/update-disposable-domains.mjs — do not edit by hand.",
  "//",
  `// Source: https://github.com/${REPOSITORY}`,
  `// Commit ${commit}, fetched ${fetched}. CC0 1.0 Universal (public domain):`,
  "// see THIRD-PARTY-NOTICES.md. Server-only: this list never reaches a browser.",
  "// Domains real people use are taken out by the allowlist in",
  "// lib/auth/disposable-domains.ts before anything is refused.",
  'import "server-only";',
  "",
  "export const DISPOSABLE_LIST_SOURCE = {",
  `  repository: "https://github.com/${REPOSITORY}",`,
  `  commit: "${commit}",`,
  `  fetched: "${fetched}",`,
  '  license: "CC0-1.0",',
  "} as const;",
  "",
  "export const DISPOSABLE_DOMAINS_RAW: readonly string[] = [",
  ...domains.map((domain) => `  "${domain}",`),
  "];",
  "",
].join("\n");

writeFileSync(OUT, body, "utf8");
console.log(`${domains.length} disposable domains written to lib/auth/disposable-domains.list.ts (commit ${commit.slice(0, 12)})`);
console.log("Next: node --use-system-ca scripts/sync-auth-domains.mjs --apply");
