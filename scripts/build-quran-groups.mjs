/**
 * Write lib/quran/groups.generated.ts: the verses that share one Uyghur
 * translation, read from the bundled QuranEnc XML.
 *
 * Run:  node scripts/build-quran-groups.mjs
 *
 * The groups are data, not a migration: they come from the RAW translation
 * file (its range markers «(160ـ161)» and its identical consecutive texts —
 * `uyghurGroups` in scripts/quran-text.mjs, ported from the desktop's 3.6),
 * never from the cleaned `quran_ayas.text_ug`. Re-run it only if that file
 * changes, and commit the output.
 */
import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";
import { multiVerseGroups, parseUyghurXml } from "./quran-text.mjs";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(repoRoot, "migration-data", "uyghur_saleh_v1.0.2-xml.1.xml");
const target = join(repoRoot, "lib", "quran", "groups.generated.ts");

if (!existsSync(source)) {
  console.error(`\nMissing ${source}\nCopy it from the desktop app's assets/seed/ folder.\n`);
  process.exit(1);
}

const groups = multiVerseGroups(parseUyghurXml(await readFile(source, "utf-8")));
const unequal = groups.filter((g) => !g.same);

const lines = [
  "// GENERATED by scripts/build-quran-groups.mjs from",
  "// migration-data/uyghur_saleh_v1.0.2-xml.1.xml — do not edit by hand.",
  "//",
  "// The runs of consecutive verses that share ONE Uyghur translation",
  `// (${groups.length} groups), as [sura, from, to]. A verse not listed is its own`,
  "// group. Read from the raw file's range markers and identical texts",
  "// (uyghurGroups, ported from the desktop's 3.6), never from text_ug.",
  "",
  "export const QURAN_GROUPS: readonly (readonly [number, number, number])[] = [",
  ...groups.map((g) => `  [${g.sura}, ${g.from}, ${g.to}],`),
  "];",
  "",
  "// The groups whose verses' texts differ, with the verse that holds the",
  "// group's (the longest) text, as [sura, from, aya]. In every other group",
  "// the verses carry the same text.",
  "export const GROUP_TEXT_AYA: readonly (readonly [number, number, number])[] = [",
  ...unequal.map((g) => `  [${g.sura}, ${g.from}, ${g.textAya}],`),
  "];",
  "",
];

await writeFile(target, lines.join("\n"), "utf-8");
console.log(`Wrote ${groups.length} groups (${unequal.length} with differing texts) to ${target}`);
