#!/usr/bin/env node
/**
 * Copy the site's email-domain lists into the database, where the Before User
 * Created hook (migration 0027) reads them (PROMPT-39, part A).
 *
 *   node scripts/sync-auth-domains.mjs                      writes the seed file only
 *   node --use-system-ca scripts/sync-auth-domains.mjs --apply   … and loads it into Supabase
 *
 * The TypeScript lists are the source of truth:
 *   - lib/auth/blocked-email-domains.ts — BLOCKED_TLDS and BLOCKED_PROVIDER_DOMAINS,
 *     the Chinese-jurisdiction rule by name;
 *   - lib/auth/disposable-domains.list.ts — the community list of throwaway
 *     domains, minus lib/auth/disposable-domains.ts's allowlist (and every
 *     common domain in lib/auth/email.ts), filtered by the same rule as
 *     `DISPOSABLE_DOMAINS` there.
 *
 * It always rewrites supabase/seed/auth_domains.sql, a single statement that
 * can also be pasted into the Supabase SQL Editor by hand;
 * tests/unit/auth-domains-sync.test.ts compares that file with the TypeScript
 * and fails until this has been run after any change to a list. `--apply`
 * then calls public.auth_domains_replace() with the service-role key from
 * .env.local, which swaps both lists in one transaction. Re-running it is
 * always safe.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";

const ROOT = process.cwd();
const SEED = join(ROOT, "supabase", "seed", "auth_domains.sql");

/**
 * The string literals of one exported array, read straight from its source
 * file. Line comments inside the array are dropped first; the lists hold
 * domain names only, which never contain quotes or slashes.
 */
function exportedStrings(file, name) {
  const source = readFileSync(join(ROOT, file), "utf8");
  const start = source.indexOf(`export const ${name}`);
  if (start < 0) throw new Error(`${name} not found in ${file}`);
  const open = source.indexOf("[", source.indexOf("=", start));
  const close = source.indexOf("];", open);
  if (open < 0 || close < 0) throw new Error(`could not read the array ${name} in ${file}`);
  const body = source
    .slice(open + 1, close)
    .split(/\r?\n/)
    .map((line) => line.replace(/\/\/.*$/, ""))
    .join("\n");
  return [...body.matchAll(/"([^"]+)"/g)].map((match) => match[1].toLowerCase());
}

const under = (host, entry) => host === entry || host.endsWith(`.${entry}`);

const blocked = [
  ...new Set([
    ...exportedStrings("lib/auth/blocked-email-domains.ts", "BLOCKED_TLDS"),
    ...exportedStrings("lib/auth/blocked-email-domains.ts", "BLOCKED_PROVIDER_DOMAINS"),
  ]),
].sort();

const allowed = [
  ...new Set([
    ...exportedStrings("lib/auth/email.ts", "COMMON_DOMAINS"),
    ...exportedStrings("lib/auth/disposable-domains.ts", "DISPOSABLE_ALLOWLIST"),
  ]),
];

const disposable = [
  ...new Set(
    exportedStrings("lib/auth/disposable-domains.list.ts", "DISPOSABLE_DOMAINS_RAW").filter(
      (entry) => !allowed.some((allow) => under(allow, entry) || under(entry, allow)),
    ),
  ),
].sort();

if (blocked.length < 5 || disposable.length < 1000) {
  throw new Error(`suspiciously short lists (${blocked.length} blocked, ${disposable.length} disposable)`);
}

const literal = (values) =>
  `array[\n${values.map((value) => `  '${value.replaceAll("'", "''")}'`).join(",\n")}\n]::text[]`;

mkdirSync(dirname(SEED), { recursive: true });
writeFileSync(
  SEED,
  [
    "-- Generated by scripts/sync-auth-domains.mjs — do not edit by hand.",
    "-- The domain lists the Before User Created hook reads (migration 0027),",
    "-- copied from the site's TypeScript: re-run the script after changing a list.",
    `-- ${blocked.length} Chinese-jurisdiction entries, ${disposable.length} disposable domains.`,
    "-- Safe to paste into the Supabase SQL Editor: it replaces both lists at once.",
    "select public.auth_domains_replace(",
    `${literal(blocked)},`,
    `${literal(disposable)}`,
    ");",
    "",
  ].join("\n"),
  "utf8",
);
console.log(`supabase/seed/auth_domains.sql: ${blocked.length} blocked, ${disposable.length} disposable`);

if (process.argv.includes("--apply")) {
  const env = {};
  for (const line of readFileSync(join(ROOT, ".env.local"), "utf8").split(/\r?\n/)) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line);
    if (match) env[match[1]] = match[2].trim().replace(/^["']|["']$/g, "");
  }
  const url = env.NEXT_PUBLIC_SUPABASE_URL;
  const key = env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) throw new Error(".env.local has no NEXT_PUBLIC_SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY");

  const response = await fetch(`${url}/rest/v1/rpc/auth_domains_replace`, {
    method: "POST",
    headers: { apikey: key, authorization: `Bearer ${key}`, "content-type": "application/json" },
    body: JSON.stringify({ p_blocked: blocked, p_disposable: disposable }),
  });
  const answer = await response.text();
  if (!response.ok) throw new Error(`auth_domains_replace answered ${response.status}: ${answer.slice(0, 300)}`);
  console.log(`database now holds ${answer}`);
}
